<?php

declare(strict_types=1);

namespace Manager\Models;

use Manager\Http\HttpException;
use Manager\Support\AtomicFile;
use Manager\Support\Config;

/**
 * Files Manager renders into runtime/coredns/ for the Corefile to import (its reload plugin
 * picks changes up within seconds): sites.conf (custom-TLD site domains) and global.conf (query log).
 */
final class DnsConfig
{
    private readonly string $dir;

    public function __construct(?string $runtimePath = null)
    {
        $this->dir = rtrim($runtimePath ?? Config::runtimePath(), '/') . '/coredns';
    }

    /**
     * TLDs answered with nginx's address: the zones of the Corefile's first server block.
     *
     * @return list<string>
     */
    public static function siteTlds(): array
    {
        $corefile = @file_get_contents(rtrim(Config::projectPath(), '/') . '/configs/coredns/Corefile');
        if (!is_string($corefile) || preg_match('/^([a-z0-9. ]+)\{/m', $corefile, $m) !== 1) {
            return [];
        }

        return array_values(array_filter(explode(' ', trim($m[1])), static fn (string $zone): bool => $zone !== '.' && $zone !== ''));
    }

    /**
     * Re-render sites.conf from env.json + hosts extras. Called after every domain change; a failed
     * write must not fail the domain save itself (the DNS panel re-syncs when opened).
     *
     * @return list<string>
     */
    public static function sync(): array
    {
        $hosts = new HostsSync();
        try {
            return (new self())->syncSites($hosts->desiredDomains((new EnvConfig())->allOrEmpty()), self::siteTlds());
        } catch (HttpException) {
            return [];
        }
    }

    /**
     * Site domains outside those TLDs (e.g. app.posapp) get an exact rewrite to nginx.
     * Exact, not per TLD: a "foo.com" site must not take over every .com name.
     *
     * @param list<string> $domains
     * @param list<string> $siteTlds
     * @return list<string> the domains that got a rule
     */
    public function syncSites(array $domains, array $siteTlds): array
    {
        $custom = array_values(array_filter(
            $domains,
            static fn (string $d): bool => DnsRecords::isHostname($d) && str_contains($d, '.')
                && !in_array(substr($d, strrpos($d, '.') + 1), $siteTlds, true),
        ));
        $out = "# Generated by Manager (site domains with a custom TLD). Do not edit.\n";
        foreach ($custom as $domain) {
            $out .= "rewrite name exact {$domain}. nginx_container. answer auto\n";
        }
        $this->writeIfChanged('sites.conf', $out);

        return $custom;
    }

    /** @return list<string> */
    public function customSiteDomains(): array
    {
        $raw = @file_get_contents($this->dir . '/sites.conf');
        preg_match_all('/^rewrite name exact (\S+)\. /m', is_string($raw) ? $raw : '', $m);

        return $m[1];
    }

    public function queryLog(): bool
    {
        $raw = @file_get_contents($this->dir . '/global.conf');

        return is_string($raw) && preg_match('/^log$/m', $raw) === 1;
    }

    public function setQueryLog(bool $on): void
    {
        $this->writeIfChanged('global.conf', $on ? "# Query log on (Manager).\nlog\n" : "# Query log off (Manager).\n");
    }

    /** Skip unchanged writes so CoreDNS does not reload for nothing. */
    private function writeIfChanged(string $name, string $content): void
    {
        $path = $this->dir . '/' . $name;
        if (@file_get_contents($path) === $content) {
            return;
        }
        if (!AtomicFile::write($path, $content)) {
            throw new HttpException('dns.record.write_failed', 500);
        }
    }
}
